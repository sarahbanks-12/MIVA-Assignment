-- Disposable teaching database. This file only creates objects; reset is explicit.
CREATE SCHEMA bank;
SET search_path = bank, public;
CREATE TABLE customers (
 customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name text NOT NULL CHECK (length(trim(full_name)) > 0),
 email text NOT NULL UNIQUE,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE accounts (
 account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id bigint REFERENCES customers,
 account_number char(10) NOT NULL UNIQUE CHECK (account_number ~ '^[0-9]{10}$'),
 account_kind text NOT NULL CHECK (account_kind IN ('customer','clearing')),
 currency char(3) NOT NULL DEFAULT 'NGN' CHECK (currency = 'NGN'),
 balance_kobo bigint NOT NULL DEFAULT 0,
 CHECK ((account_kind='customer' AND customer_id IS NOT NULL AND balance_kobo>=0)
     OR (account_kind='clearing' AND customer_id IS NULL))
);
CREATE UNIQUE INDEX accounts_one_clearing ON accounts(account_kind) WHERE account_kind='clearing';
CREATE TABLE transfers (
 transfer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_key text NOT NULL UNIQUE CHECK (length(request_key) BETWEEN 1 AND 100),
 source_account bigint NOT NULL REFERENCES accounts,
 destination_account bigint NOT NULL REFERENCES accounts,
 amount_kobo bigint NOT NULL CHECK (amount_kobo>0),
 kind text NOT NULL CHECK (kind IN ('deposit','withdrawal','transfer','reversal')),
 reversal_of bigint UNIQUE REFERENCES transfers,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 CHECK (source_account<>destination_account),
 CHECK ((kind='reversal') = (reversal_of IS NOT NULL))
);
CREATE TABLE ledger_entries (
 transfer_id bigint NOT NULL REFERENCES transfers,
 account_id bigint NOT NULL REFERENCES accounts,
 delta_kobo bigint NOT NULL CHECK (delta_kobo<>0),
 PRIMARY KEY (transfer_id,account_id)
);
-- For this wallet subledger a debit reduces the source wallet; this is not
-- a complete bank general ledger with assets, liabilities, income and expense.
CREATE FUNCTION validate_posting() RETURNS trigger LANGUAGE plpgsql SET search_path=bank,pg_temp AS $$
DECLARE t transfers; n integer; total numeric; matched integer;
BEGIN
 SELECT * INTO t FROM transfers WHERE transfer_id=NEW.transfer_id;
 SELECT count(*),coalesce(sum(delta_kobo),0),
 count(*) FILTER (WHERE (account_id=t.source_account AND delta_kobo=-t.amount_kobo)
 OR (account_id=t.destination_account AND delta_kobo=t.amount_kobo))
 INTO n,total,matched FROM ledger_entries WHERE transfer_id=t.transfer_id;
 IF n<>2 OR total<>0 OR matched<>2 THEN
  RAISE EXCEPTION 'Transfer % must have its two balanced postings',t.transfer_id;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER transfer_postings AFTER INSERT ON transfers
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_posting();

CREATE FUNCTION post_transfer(p_key text,p_source bigint,p_destination bigint,
 p_amount bigint,p_kind text DEFAULT 'transfer',p_reversal bigint DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=bank,pg_temp AS $$
DECLARE old transfers; src accounts; dst accounts; original transfers; result bigint;
BEGIN
 IF p_key IS NULL OR length(p_key) NOT BETWEEN 1 AND 100 OR p_source IS NULL
 OR p_destination IS NULL OR p_amount IS NULL OR p_amount<=0
 OR p_source=p_destination OR p_kind IS NULL THEN RAISE EXCEPTION 'Invalid request'; END IF;
 -- Serialize retries sharing a key. Hash collisions only cause extra waiting.
 PERFORM pg_advisory_xact_lock(hashtextextended(p_key,0));
 SELECT * INTO old FROM transfers WHERE request_key=p_key;
 IF FOUND THEN
  IF (old.source_account,old.destination_account,old.amount_kobo,old.kind,old.reversal_of)
   IS DISTINCT FROM (p_source,p_destination,p_amount,p_kind,p_reversal)
   THEN RAISE EXCEPTION 'Idempotency key reused with different parameters'; END IF;
  RETURN old.transfer_id;
 END IF;
 -- Both rows always locked in ascending ID order to avoid opposite-transfer deadlocks.
 PERFORM account_id FROM accounts WHERE account_id IN (p_source,p_destination)
 ORDER BY account_id FOR UPDATE;
 SELECT * INTO src FROM accounts WHERE account_id=p_source;
 SELECT * INTO dst FROM accounts WHERE account_id=p_destination;
 IF src.account_id IS NULL OR dst.account_id IS NULL THEN RAISE EXCEPTION 'Unknown account'; END IF;
 IF p_kind='deposit' AND NOT(src.account_kind='clearing' AND dst.account_kind='customer')
 OR p_kind='withdrawal' AND NOT(src.account_kind='customer' AND dst.account_kind='clearing')
 OR p_kind='transfer' AND NOT(src.account_kind='customer' AND dst.account_kind='customer')
 THEN RAISE EXCEPTION 'Account kinds do not match operation'; END IF;
 IF p_kind='reversal' THEN
  IF EXISTS(SELECT 1 FROM transfers WHERE reversal_of=p_reversal) THEN RAISE EXCEPTION 'Already reversed'; END IF;
  SELECT * INTO original FROM transfers WHERE transfer_id=p_reversal;
  IF original.transfer_id IS NULL OR original.kind='reversal'
    OR (original.source_account,original.destination_account,original.amount_kobo)
    IS DISTINCT FROM (p_destination,p_source,p_amount)
    THEN RAISE EXCEPTION 'Invalid reversal'; END IF;
 END IF;
 IF src.account_kind='customer' AND src.balance_kobo<p_amount
 THEN RAISE EXCEPTION 'Insufficient funds'; END IF;
 INSERT INTO transfers(request_key,source_account,destination_account,amount_kobo,kind,reversal_of)
 VALUES(p_key,p_source,p_destination,p_amount,p_kind,p_reversal) RETURNING transfer_id INTO result;
 UPDATE accounts SET balance_kobo=balance_kobo-p_amount WHERE account_id=p_source;
 UPDATE accounts SET balance_kobo=balance_kobo+p_amount WHERE account_id=p_destination;
 INSERT INTO ledger_entries VALUES(result,p_source,-p_amount),(result,p_destination,p_amount);
 RETURN result;
END $$;
REVOKE ALL ON FUNCTION post_transfer(text,bigint,bigint,bigint,text,bigint) FROM PUBLIC;
-- Dedicated local role: application cannot edit balances or history directly.
CREATE ROLE cedar_app NOLOGIN;
GRANT USAGE ON SCHEMA bank TO cedar_app;
GRANT SELECT ON ALL TABLES IN SCHEMA bank TO cedar_app;
